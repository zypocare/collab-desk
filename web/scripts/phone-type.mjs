// Builds src/mobile-type.css: on phones, every font size in the Studio's styles is folded into
// one even scale (like Instagram's), weights are evened out, letter-spacing is reset and small
// capital labels become normal text. Runs before `dev` and `build`, so new styles are covered.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const src = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'src');
const FILES = ['app.css', 'studio.css'];

// Phone scale: 11 · 12.5 · 13.5 · 15 · 16 · 18 · 22 · 26 · 32
const size = (v) => (v <= 11.5 ? 11 : v <= 13 ? 12.5 : v <= 14.5 ? 13.5 : v <= 16.5 ? 15 : v <= 18 ? 16 : v <= 22 ? 18 : v <= 28 ? 22 : v <= 36 ? 26 : 32);
const weight = (w) => (w >= 750 ? 700 : w === 650 ? 600 : w);

// Secondary lines (dates, hints, sub-labels) are one step smaller than the main text, like Instagram.
const META = /(^|[\s>+~])(small|time)\b|\.(hint|sub|tm|m|muted|dr-sub|meta|when|ago|note|caption)(?![\w-])/;
const isMeta = (prelude) => prelude.split(/,(?![^(]*\))/).every((s) => META.test(s.trim().split(/[\s>+~]+/).pop() ?? ''));

/** Top-level rules of a stylesheet: { prelude, body } with nested blocks kept as text. */
function blocks(css) {
	const out = [];
	let i = 0;
	while (i < css.length) {
		const open = css.indexOf('{', i);
		if (open < 0) break;
		let depth = 1;
		let j = open + 1;
		while (j < css.length && depth) {
			if (css[j] === '{') depth++;
			else if (css[j] === '}') depth--;
			j++;
		}
		out.push({ prelude: css.slice(i, open).trim(), body: css.slice(open + 1, j - 1) });
		i = j;
	}
	return out;
}

function scope(selector) {
	return selector
		.split(/,(?![^(]*\))/)
		.map((s) => s.trim())
		.filter((s) => s && !s.startsWith('[data-side="brand"]') && !/^(html|:root|::|@)/.test(s) && !s.includes('view-transition'))
		.map((s) => (s.startsWith('[data-side="studio"]') ? s : s.startsWith('body') ? `[data-side="studio"] ${s}` : `[data-side="studio"] ${s}`));
}

function rules(css, out, inPhone) {
	for (const { prelude, body } of blocks(css.replace(/\/\*[\s\S]*?\*\//g, ''))) {
		if (prelude.startsWith('@')) {
			if (/^@(keyframes|font-face|page|-webkit-keyframes)/.test(prelude) || /print|min-width|prefers-reduced-motion|hover:\s*hover/.test(prelude)) continue;
			rules(body, out, inPhone);
			continue;
		}
		const decl = [];
		const fs_ = body.match(/(?:^|;)\s*font-size\s*:\s*([\d.]+)px/);
		const fw = body.match(/(?:^|;)\s*font-weight\s*:\s*(\d+)/);
		const caps = /text-transform\s*:\s*uppercase/.test(body);
		const ls = /letter-spacing\s*:/.test(body);
		if (fs_) decl.push(`font-size:${caps ? 13.5 : isMeta(prelude) ? (+fs_[1] <= 12 ? 12 : 13.5) : size(+fs_[1])}px`);
		if (fw && weight(+fw[1]) !== +fw[1]) decl.push(`font-weight:${weight(+fw[1])}`);
		if (caps) decl.push('text-transform:none');
		if (ls || caps) decl.push('letter-spacing:normal');
		if (!decl.length) continue;
		const sel = scope(prelude);
		if (sel.length) out.push(`${sel.join(',')}{${decl.join(';')}}`);
	}
}

const out = [];
for (const f of FILES) rules(fs.readFileSync(path.join(src, f), 'utf8'), out, false);
const css = `/* Generated by scripts/phone-type.mjs: do not edit. Phone type scale for the Studio. */\n@media (max-width:760px){\n${out.map((r) => '  ' + r).join('\n')}\n}\n`;
// Windows line endings, like the rest of the repo, so a local build leaves no changes behind.
fs.writeFileSync(path.join(src, 'mobile-type.css'), css.replaceAll('\n', '\r\n'));
console.log(`phone-type: ${out.length} rules`);
